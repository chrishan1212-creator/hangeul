/** 정규화: 공백, 물음표, 느낌표, 마침표 등을 제거하고 비교하기 쉽게 만든다 */
function normalize(text: string): string {
  return text.replace(/[\s!?.,~♥ㅎㅋㅜㅠ]/g, "").trim();
}

export interface MatchResult {
  word: string;
  emoji: string;
  matched: boolean;
}

/**
 * 인식된 음성 텍스트에서 가장 잘 맞는 단어와 이모지를 찾는다.
 * 1) 정확히 일치하는 단어 우선
 * 2) 사전에 있는 단어가 문장 안에 포함되어 있으면 그중 가장 긴 단어 선택
 * 3) 못 찾으면 원래 들린 말 그대로 보여주고 기본 이모지를 붙인다
 */
export function matchWordToEmoji(transcript: string): MatchResult {
  const cleaned = normalize(transcript);
  if (!cleaned) {
    return { word: "", emoji: "🎤", matched: false };
  }

  if (WORD_EMOJI_MAP[cleaned]) {
    return { word: cleaned, emoji: WORD_EMOJI_MAP[cleaned], matched: true };
  }

  let bestKey = "";
  for (const key of Object.keys(WORD_EMOJI_MAP)) {
    if (cleaned.includes(key) && key.length > bestKey.length) {
      bestKey = key;
    }
  }

  if (bestKey) {
    return { word: bestKey, emoji: WORD_EMOJI_MAP[bestKey], matched: true };
  }

  return { word: cleaned, emoji: "💬", matched: false };
}
